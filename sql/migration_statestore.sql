-- ====================================================================
-- MIGRATION: BOT SESSIONS & STATE STORE
-- รองรับระบบ State Persistence สำหรับ Discord Bot และ Web Session Handshake
-- ====================================================================

CREATE TABLE IF NOT EXISTS public.bot_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace TEXT NOT NULL,
    key TEXT NOT NULL,
    value JSONB NOT NULL DEFAULT '{}'::jsonb,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_bot_sessions_ns_key UNIQUE (namespace, key)
);

-- Index สำหรับค้นหา namespace + key อย่างรวดเร็ว
CREATE INDEX IF NOT EXISTS idx_bot_sessions_lookup 
ON public.bot_sessions (namespace, key);

-- Index สำหรับ Query Expired Records / Cleanup Job
CREATE INDEX IF NOT EXISTS idx_bot_sessions_expiry 
ON public.bot_sessions (expires_at);

-- Trigger อัปเดต updated_at อัตโนมัติ
CREATE OR REPLACE FUNCTION public.handle_bot_sessions_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_bot_sessions_updated_at ON public.bot_sessions;
CREATE TRIGGER tr_bot_sessions_updated_at
    BEFORE UPDATE ON public.bot_sessions
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_bot_sessions_updated_at();

-- Comment กำกับตาราง
COMMENT ON TABLE public.bot_sessions IS 'ที่เก็บสถานะชั่วคราวของ Bot และ Web Handshake แบบทนทานต่อการรีสตาร์ทบอท';
